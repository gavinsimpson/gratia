# Post hoc diagnostic follow-up, kept separate from the primary coverage results.
args <- commandArgs(TRUE)
directory <- if (length(args)) args[1L] else
  "/Users/gavin/work/git/gratia/research-archives/mh-adjustment-2026-10-15-followup"
main <- if (length(args) >= 2L) args[2L] else
  "/Users/gavin/work/git/gratia/research-archives/mh-adjustment-2026-10-15-main"
destination <- if (length(args) >= 3L) args[3L] else "notes/posterior-chains"
RNGkind("L'Ecuyer-CMRG", "Inversion", "Rejection")
Sys.setenv(OMP_NUM_THREADS = "1", OPENBLAS_NUM_THREADS = "1", VECLIB_MAXIMUM_THREADS = "1")
source("notes/posterior-chains/mh-adjustment-functions.R")
dir.create(directory, recursive = TRUE, showWarnings = FALSE)
protocol <- list(reason = paste("Post hoc follow-up of rare-binary GAM dataset 73:",
  "tail ESS below 400 in the primary run."), case = "binomial_rare",
  replicate = 73L, n_draws = 64000L, burnin = 16000L,
  source_hashes = tools::md5sum(c("R/sampling-mh-adjustment.R",
    "notes/posterior-chains/mh-adjustment-functions.R")))
path <- file.path(directory, "rare-73.rds")
if (file.exists(path)) {
  saved <- readRDS(path)
  fields <- setdiff(names(protocol), "source_hashes")
  stopifnot(identical(saved$protocol[fields], protocol[fields]))
  roots <- c(".", file.path(directory, "sources"))
  matching <- vapply(roots, function(root) {
    paths <- file.path(root, names(saved$protocol$source_hashes))
    all(file.exists(paths)) && identical(unname(tools::md5sum(paths)),
      unname(saved$protocol$source_hashes))
  }, logical(1L))
  if (!any(matching)) stop("The saved follow-up has no matching execution sources.")
  cat("Reusing saved follow-up generated by:", roots[which(matching)[1L]], "\n")
  results <- saved$results
} else {
  results <- adjustment_study_replicate("binomial_rare", 73L, 64000L, 16000L)
  saveRDS(list(protocol = protocol, results = results), path)
}
original <- readRDS(file.path(main, "binomial_rare-00071.rds"))$results[[3L]]
rows <- list()
for (r in results) {
  old <- Filter(function(x) x$engine == r$engine, original)[[1L]]
  stopifnot(r$status == "OK", old$status == "OK",
    isTRUE(all.equal(r$log_sp, old$log_sp, tolerance = 1e-10)),
    all(r$chains$retained == 16000L), all(r$chains$burnin == 16000L))
  for (sampler in c("conditional_mh", "adjusted_mh", "unconditional_gaussian")) {
    s <- r$summary[[sampler]]
    d <- rbind(s$coefficient_diagnostics[, c("rhat", "ess_bulk", "ess_tail")],
      s$diagnostics[, c("rhat", "ess_bulk", "ess_tail")])
    cat(r$engine, sampler, "Rhat", max(d$rhat), "bulk/tail ESS",
      min(d$ess_bulk), min(d$ess_tail), "\n")
    for (quantity in unique(s$intervals$quantity)) {
      a <- old$summary[[sampler]]$intervals
      b <- s$intervals
      a <- a[a$quantity == quantity, ]; b <- b[b$quantity == quantity, ]
      stopifnot(identical(a$truth, b$truth), all(a$upper > a$lower))
      interior <- a$point > 1L & a$point < 11L
      rows[[length(rows) + 1L]] <- data.frame(case = r$case, replicate = 73L,
        engine = r$engine, method = r$method, sampler = sampler, quantity = quantity,
        max_rhat = max(d$rhat), min_bulk_ess = min(d$ess_bulk), min_tail_ess = min(d$ess_tail),
        passes = max(d$rhat) < 1.01 && min(d$ess_bulk) >= 400 && min(d$ess_tail) >= 400,
        interior_coverage_change = mean(b$covered[interior] - a$covered[interior]),
        max_endpoint_change_over_width = max(pmax(abs(a$lower - b$lower),
          abs(a$upper - b$upper)) / (a$upper - a$lower)))
    }
  }
}
utils::write.csv(do.call(rbind, rows),
  file.path(destination, "mh-adjustment-followup.csv"), row.names = FALSE)
cat("The primary study's intervals and denominators have not been replaced.\n")
